export function element<K extends keyof typeof tags>(id: K): HTMLElementTagNameMap[(typeof tags)[K]] {
  const node = document.getElementById(id);
  if (!node || node.localName !== tags[id]) throw new Error(`Missing <${tags[id]}> #${id}`);
  // The tag was checked above; the assertion preserves the literal ID/tag relation.
  return node as HTMLElementTagNameMap[(typeof tags)[K]];
}
